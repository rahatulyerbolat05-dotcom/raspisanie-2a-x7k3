function P(pair, name, teacher, room, tag) {
  return { pair: pair, name: name, teacher: teacher || "", room: room || "", tag: tag || "" };
}
function SPLIT(pair, numCls, denomCls) {
  // numCls / denomCls можно передать как null — значит в эту неделю урока нет.
  function one(c) { return c ? { pair: pair, name: c.name, teacher: c.teacher || "", room: c.room || "", tag: c.tag || "" } : null; }
  return { pair: pair, split: true, num: one(numCls), denom: one(denomCls) };
}

